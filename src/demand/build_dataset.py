"""
build_dataset.py - Step 1: Build GNN training dataset from Manhattan parquet
=============================================================================
Converts the filtered Manhattan hourly ridership parquet into the normalized
daily profile dataset used to train the backbone GNN.

Requires:
    data/nyc/raw/mta_manhattan_2022_2024.parquet  (generated by prepare_data.py)
    data/nyc/mta_manhattan_lookup.csv             (included in repo)
    data/nyc/penn_corridor_spikes_2022_2024.csv   (included in repo)

Usage:
    python src/demand/build_dataset.py

Outputs (all in data/nyc/manhattan/):
    daily_profiles.parquet       -(date, sid, h00..h23, daily_total, is_event)
    event_labels.csv             - per-day event flag and Penn corridor ratio
    baseline_profile.parquet     - mean hourly profile by (sid, day-of-week, hour)
    baseline_daily_totals.parquet - median daily total by (sid, day-of-week)
    station_lookup.csv           - station metadata (sid, name, lat, lon)
"""

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]

# Paths
PARQ       = ROOT / "data/nyc/raw/mta_manhattan_2022_2024.parquet"
LKP_CSV    = ROOT / "data/nyc/mta_manhattan_lookup.csv"
PENN_SPIKES = ROOT / "data/nyc/penn_corridor_spikes_2022_2024.csv"
OUT_DIR    = ROOT / "data/nyc/manhattan"

# Parameters
PENN_EVENT_THRESHOLD = 1.2   # Penn corridor ratio threshold for event labeling
MIN_DAILY_RIDERS     = 10    # stations with fewer daily riders use uniform profile
DATE_START           = "2022-01-01"
DATE_END             = "2024-12-31"

OUT_DIR.mkdir(parents=True, exist_ok=True)

# Validate inputs
for p in [PARQ, LKP_CSV, PENN_SPIKES]:
    if not p.exists():
        msg = f"Required file not found: {p}"
        if p == PARQ:
            msg += "\n  Run first: python src/demand/prepare_data.py"
        raise FileNotFoundError(msg)

# 1) Load ridership
print("Loading Manhattan hourly ridership...")
df = pd.read_parquet(PARQ)
df["ts"]  = pd.to_datetime(df["ts"])
df["sid"] = df["sid"].astype(int)

print("Pivoting to hourly matrix...")
X = df.pivot(index="ts", columns="sid", values="ridership").sort_index()

full_idx = pd.date_range(DATE_START, f"{DATE_END} 23:00", freq="h")
X = X.reindex(full_idx).fillna(0.0)
X.index.name = "ts"

sid_order = X.columns.tolist()
T, N = X.shape
print(f"  Matrix: {T} hours × {N} stations")

# 2) Event labels (Penn corridor)
print("Loading Penn corridor event labels...")
spikes = pd.read_csv(PENN_SPIKES)
spikes["date"] = pd.to_datetime(spikes["date"]).dt.date
penn_event_dates = set(
    spikes.loc[spikes["ratio"] >= PENN_EVENT_THRESHOLD, "date"]
)
print(f"  Event days (ratio >= {PENN_EVENT_THRESHOLD}): {len(penn_event_dates)}")

# 3) Compute normalized hourly profiles
print("Computing normalized profiles per day...")
X_vals = X.values.astype(np.float32)
dates  = X.index.date
unique_dates = sorted(set(dates))
records = []

for d in unique_dates:
    mask = dates == d
    day_matrix = X_vals[mask]
    if day_matrix.shape[0] != 24:
        continue

    daily_total = day_matrix.sum(axis=0)
    profile = np.where(
        daily_total[None, :] >= MIN_DAILY_RIDERS,
        day_matrix / np.maximum(daily_total[None, :], 1.0),
        1.0 / 24.0,
    )

    is_event = int(d in penn_event_dates)
    for i, sid in enumerate(sid_order):
        row = {"date": d, "sid": sid, "is_event": is_event,
               "daily_total": daily_total[i]}
        for h in range(24):
            row[f"h{h:02d}"] = float(profile[h, i])
        records.append(row)

print(f"  Generated {len(records):,} records (day × station)")

# 4) Save daily_profiles.parquet
print("Saving daily_profiles.parquet...")
profiles_df = pd.DataFrame(records)
profiles_df["date"] = pd.to_datetime(profiles_df["date"])
out_profiles = OUT_DIR / "daily_profiles.parquet"
profiles_df.to_parquet(out_profiles, index=False)
print(f"  → {out_profiles}  {profiles_df.shape}")

# 5) Save event_labels.csv
print("Saving event_labels.csv...")
all_days = pd.DataFrame({"date": pd.to_datetime(sorted(unique_dates))})
all_days["is_event"] = all_days["date"].dt.date.isin(penn_event_dates).astype(int)
all_days["event_source"] = "penn"
spikes_copy = spikes.copy()
spikes_copy["date"] = pd.to_datetime(spikes_copy["date"])
all_days = all_days.merge(spikes_copy[["date", "ratio"]], on="date", how="left")
all_days = all_days.rename(columns={"ratio": "penn_ratio"})
out_labels = OUT_DIR / "event_labels.csv"
all_days.to_csv(out_labels, index=False)
n_events = int(all_days["is_event"].sum())
print(f"  → {out_labels}  ({len(all_days)} days, {n_events} events)")

# 6) Compute baseline profiles (normal days only)
print("Computing baseline profiles...")
normal_profiles = profiles_df[profiles_df["is_event"] == 0].copy()
normal_profiles["dow"] = pd.to_datetime(normal_profiles["date"]).dt.dayofweek

hour_cols = [f"h{h:02d}" for h in range(24)]
baseline_records = []
for (sid, dow), group in normal_profiles.groupby(["sid", "dow"]):
    means = group[hour_cols].mean().values
    for h in range(24):
        baseline_records.append({"sid": sid, "dow": dow, "hour": h,
                                  "mean_profile": float(means[h])})

baseline_df = pd.DataFrame(baseline_records)
out_baseline = OUT_DIR / "baseline_profile.parquet"
baseline_df.to_parquet(out_baseline, index=False)
print(f"  → {out_baseline}  {baseline_df.shape}")

# Baseline daily totals by (sid, day-of-week) - used as Feature 6 in GNN
normal_profiles["daily_total"] = normal_profiles["daily_total"].astype(float)
baseline_daily = (
    normal_profiles.groupby(["sid", "dow"])["daily_total"]
    .median()
    .reset_index()
    .rename(columns={"daily_total": "median_daily_total"})
)
out_bdt = OUT_DIR / "baseline_daily_totals.parquet"
baseline_daily.to_parquet(out_bdt, index=False)
print(f"  → {out_bdt}")

# 7) Save station_lookup.csv
print("Saving station_lookup.csv...")
lkp = pd.read_csv(LKP_CSV)
lkp["sid"] = lkp["sid"].astype(int)
lkp = lkp.set_index("sid").loc[sid_order].reset_index()
out_lkp = OUT_DIR / "station_lookup.csv"
lkp.to_csv(out_lkp, index=False)
print(f"  → {out_lkp}  ({len(lkp)} stations)")

# Summary
print()
print("=" * 55)
print(f"Dataset ready in: {OUT_DIR}")
print(f"  Stations    : {N}")
print(f"  Total days  : {len(all_days)}")
print(f"  Event days  : {n_events}  (Penn corridor, ratio >= {PENN_EVENT_THRESHOLD})")
print("=" * 55)
print("\nNext step:")
print("  python src/ml/disaggregation/train.py")
